# PATH 操作の共通ヘルパ。以降のファイル（01, 11, 13 など）から使い、
# 最後に 99-cleanup.sh で unset する。
#
# どちらもディレクトリが実在し、かつまだ PATH に含まれていないときだけ追加する。
# 存在チェックにより、そのディレクトリを持たないマシンでは何もしない。
# 重複チェックは ":$PATH:" に対する完全一致で行う（部分一致で誤判定しないため）。

_prepend_path() {
    if [ -d "$1" ]; then
        case ":$PATH:" in
            *":$1:"*) ;;                  # 既に入っている
            *) PATH="$1:$PATH" ;;
        esac
    fi
}

_append_path() {
    if [ -d "$1" ]; then
        case ":$PATH:" in
            *":$1:"*) ;;                  # 既に入っている
            *) PATH="$PATH:$1" ;;
        esac
    fi
}
